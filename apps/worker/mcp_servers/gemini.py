"""Gemini image generation (bytes only).

Adapted from the reference ``shared/gemini/image_generator.py`` — stripped of
cost-tracking and CDN upload. Returns raw image bytes; the caller uploads to S3.
Gemini-only: the Unsplash path from the source ``images_search`` is dropped.
"""

from __future__ import annotations

import logging
import os

from google import genai
from google.genai import types

logger = logging.getLogger("worker.mcp.gemini")

DEFAULT_MODEL = os.environ.get("GEMINI_IMAGE_GEN_MODEL", "gemini-3.1-flash-image-preview")


async def generate_image_bytes(
    prompt: str,
    *,
    model: str | None = None,
    aspect_ratio: str = "1:1",
    resolution: str = "2K",
) -> tuple[bytes, str]:
    """Generate one image from ``prompt`` via Gemini. Returns ``(bytes, mime_type)``.

    Uses ``GEMINI_API_KEY`` from the environment (``genai.Client()`` reads it).
    Raises ``RuntimeError`` if the model returns no image.
    """
    client = genai.Client()  # reads GEMINI_API_KEY / GOOGLE_API_KEY from env
    response = await client.aio.models.generate_content(
        model=model or DEFAULT_MODEL,
        contents=[prompt],
        config=types.GenerateContentConfig(
            image_config=types.ImageConfig(aspect_ratio=aspect_ratio, image_size=resolution)
        ),
    )

    for part in response.parts or []:
        if part.text is not None:
            logger.info("[gemini] text part: %s", part.text)
        elif part.inline_data is not None:
            mime = part.inline_data.mime_type or "image/png"
            return part.inline_data.data, mime

    raise RuntimeError("No image was generated by the model")
